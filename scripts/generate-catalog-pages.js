const normalizeSpecEntries = (machine) => {
  const specs = machine.specs || {};
  const entries = Object.entries(specs)
    .filter(([, value]) => value !== undefined && value !== null && String(value).trim() !== '')
    .map(([key, value]) => ({
      key,
      label: specLabelMap[key] || key,
      value,
    }))
    .sort((left, right) => {
      const leftIndex = specOrder.indexOf(left.key);
      const rightIndex = specOrder.indexOf(right.key);
      const normalizedLeft = leftIndex === -1 ? Number.MAX_SAFE_INTEGER : leftIndex;
      const normalizedRight = rightIndex === -1 ? Number.MAX_SAFE_INTEGER : rightIndex;
      return normalizedLeft - normalizedRight;
    });

  if (entries.length) return entries;

  return [
    { key: 'categoria', label: 'Categoria', value: machine.category },
    { key: 'disponibilidade', label: 'Disponibilidade', value: getMachineStatusLabel(machine) },
    { key: 'aplicacao', label: 'Aplica&ccedil;&atilde;o', value: 'Processos industriais de borracha' },
  ];
};

