const writeProductPages = () => {
  fs.mkdirSync(machinesDir, { recursive: true });
  const activeSlugs = new Set(activeMachines.map((machine) => machine.slug));

  fs.readdirSync(machinesDir, { withFileTypes: true }).forEach((entry) => {
    if (!entry.isDirectory() || activeSlugs.has(entry.name)) return;

    const entryDir = path.join(machinesDir, entry.name);
    const indexPath = path.join(entryDir, 'index.html');
    const indexContent = fs.existsSync(indexPath) ? fs.readFileSync(indexPath, 'utf8') : '';

    if (indexContent.includes(generatedMarker)) {
      fs.rmSync(entryDir, { recursive: true, force: true });
    }
  });

  activeMachines.forEach((machine) => {
    const targetDir = path.join(machinesDir, machine.slug);
    fs.mkdirSync(targetDir, { recursive: true });
    fs.writeFileSync(path.join(targetDir, 'index.html'), renderProductPage(machine), 'utf8');
  });

  if (activeMachines.length) {
    fs.writeFileSync(path.join(machinesDir, 'index.html'), renderProductPage(activeMachines[0]), 'utf8');
  }
};

const writeSitemap = () => {
  const urls = [
    ...baseRoutes.map((route) => ({
      loc: `${siteUrl}${route.loc}`,
      priority: route.priority,
    })),
    ...activeMachines
      .filter((machine) => machine.indexable !== false)
      .map((machine) => ({
        loc: productUrl(machine),
        priority: '0.8',
      })),
  ];

  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls
  .map(
    (url) => `  <url>
    <loc>${escapeHtml(url.loc)}</loc>
    <lastmod>${updatedAt}</lastmod>
    <changefreq>weekly</changefreq>
    <priority>${url.priority}</priority>
  </url>`,
  )
  .join('\n')}
</urlset>
`;

  fs.writeFileSync(sitemapPath, sitemap, 'utf8');
};

const writeRobots = () => {
  const robots = `User-agent: *
Allow: /

Sitemap: ${siteUrl}/sitemap.xml
`;

  fs.writeFileSync(robotsPath, robots, 'utf8');
};

