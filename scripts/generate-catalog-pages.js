const getProductSpecLucideName = (key, label) => {
  if (key && productSpecIconMap[key]) {
    return productSpecIconMap[key];
  }

  const normalized = stripHtml(label).toLowerCase();

  if (/capacidade|pot[e\u00ea]ncia|press[a\u00e3]o|largura|corte/.test(normalized)) {
    return 'gauge';
  }

  if (/modelo/.test(normalized)) {
    return 'tag';
  }

  if (/ano/.test(normalized)) {
    return 'calendar-days';
  }

  if (/acionamento/.test(normalized)) {
    return 'settings-2';
  }

  if (/tens[a\u00e3]o|voltagem|volts?/.test(normalized)) {
    return 'zap';
  }

  if (/aplica/.test(normalized)) {
    return 'crosshair';
  }

  if (/condi|estado|dispon/.test(normalized)) {
    return 'badge-check';
  }

  if (/dimens|peso|modelo|ano/.test(normalized)) {
    return 'ruler';
  }

  return 'circle-check';
};

