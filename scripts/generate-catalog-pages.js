const decodeHtml = (value) =>
  String(value || '')
    .replace(/&#(\d+);/g, (_, code) => String.fromCharCode(Number(code)))
    .replace(/&#x([0-9a-f]+);/gi, (_, code) => String.fromCharCode(parseInt(code, 16)))
    .replace(/&[a-zA-Z#0-9]+;/g, (entity) => entityMap[entity] || entity);

const stripHtml = (value) => decodeHtml(value).replace(/<[^>]*>/g, '').replace(/\s+/g, ' ').trim();

const escapeHtml = (value) =>
  String(value || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');

const escapeAttr = (value) => escapeHtml(value).replace(/`/g, '&#096;');

const toAsciiEntities = (value) =>
  Array.from(String(value || ''))
    .map((char) => {
      const code = char.codePointAt(0);
      return code > 127 ? `&#${code};` : char;
    })
    .join('');

const htmlText = (value) => toAsciiEntities(escapeHtml(stripHtml(value)));

const stringifyJsonAscii = (value) =>
  JSON.stringify(value, null, 2).replace(/[^\x00-\x7F]/g, (char) => {
    const code = char.charCodeAt(0).toString(16).padStart(4, '0');
    return `\\u${code}`;
  });

